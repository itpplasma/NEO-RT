! test/check_collisional_layer_table.py checks it with finite differences.
! This is a large-aspect-ratio local closure, not a finite-width resonance
! solver. Passing/loss coupling is omitted, and the same factor is assumed
! for diffusion and torque. See doc/collisional_layer.md for the validated
! interpolation, asymptotic limits and explicitly rejected parameter region.
