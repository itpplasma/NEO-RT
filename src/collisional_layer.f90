    pure function collisional_layer_factor(nu_d, eta, eps, etatp, etadt, &
                                           abs_dOmega_deta) result(ratio)
        ! Layer factor R for one resonance root with explicit local geometry/rate.
        ! Passing particles have no trapped-domain boundaries: R = 1 (documented
        ! limitation; the passing/loss coupling is not modelled here).
        real(dp), intent(in) :: nu_d, eps, etatp, etadt
        real(dp), intent(in) :: eta          ! resonance pitch (1-xi^2)/B at root
        real(dp), intent(in) :: abs_dOmega_deta  ! |dOmega/deta| at root = |eta_res(2)|
        real(dp) :: ratio
        real(dp) :: delta_eta, d_tp, d_dt

        ratio = 1.0_dp
        if (eta <= etatp) return  ! passing particle

        delta_eta = layer_delta_eta(nu_d, eta, eps, etatp, etadt, abs_dOmega_deta)
        if (delta_eta <= 0.0_dp) return  ! degenerate width -> collisionless limit

        d_tp = eta - etatp
        d_dt = etadt - eta
        ratio = layer_ratio(d_dt/delta_eta, d_tp/delta_eta)
    end function collisional_layer_factor

    pure function layer_delta_eta(nu_d, eta, eps, etatp, etadt, abs_dOmega_deta) &
        result(delta_eta)
        ! Collisional layer width in eta-space,
        !   delta_eta = (D_eta_ba / |dOmega/deta|)^(1/3),
        ! with the large-aspect closed-form bounce-averaged pitch diffusion
        !   D_eta_ba = 2 nu_d eta <(1 - eta B)/B>_b
        !            = 2 nu_d eta (2 eps eta) [E(m)/K(m) - (1 - m)],
        !   m = (etadt - eta)/(etadt - etatp).
        ! With B=B0(1-eps*cos(theta)), sin(theta/2)=sqrt(m)*sin(chi),
        ! the bounce measure is dchi/sqrt(1-m*sin(chi)**2). Integrating
        ! m*cos(chi)**2 gives E(m)/K(m)-(1-m). m=0 is deeply trapped.
        ! This keeps the leading order in eps, consistently with the local
        ! two-boundary approximation used for R.
        real(dp), intent(in) :: nu_d, eta, eps, etatp, etadt, abs_dOmega_deta
        real(dp) :: delta_eta
        real(dp) :: m, shape_factor, D_eta_ba
        real(dp), parameter :: M_MIN = 1.0e-6_dp, M_MAX = 1.0_dp - 1.0e-6_dp
        real(dp), parameter :: ONE_THIRD = 1.0_dp/3.0_dp

        m = (etadt - eta)/(etadt - etatp)
        m = min(max(m, M_MIN), M_MAX)
        shape_factor = comp_ellint_e(m)/comp_ellint_k(m) - (1.0_dp - m)
        D_eta_ba = 2.0_dp*nu_d*eta*(2.0_dp*eps*eta)*shape_factor

        if (D_eta_ba <= 0.0_dp .or. abs_dOmega_deta <= 0.0_dp) then
            delta_eta = 0.0_dp
            return
        end if
        delta_eta = (D_eta_ba/abs_dOmega_deta)**ONE_THIRD
    end function layer_delta_eta

    pure function layer_ratio(d_dt_scaled, d_tp_scaled) result(ratio)
        ! No extrapolation of the table: use derived limits or fail closed.
        real(dp), intent(in) :: d_dt_scaled, d_tp_scaled
        real(dp) :: ratio, a, b

        ratio = narrow_layer_ratio(d_dt_scaled, d_tp_scaled)
        if (ratio >= 0.0_dp) return
        if (min(d_dt_scaled, d_tp_scaled) >= TABLE_MAX) then
            ratio = 1.0_dp + reflecting_tail(d_dt_scaled) + absorbing_tail(d_tp_scaled)
            return
        end if
        a = min(d_dt_scaled, TABLE_MAX)
        b = min(d_tp_scaled, TABLE_MAX)
        ratio = interpolated_ratio(a, b)
        if (d_dt_scaled > TABLE_MAX) ratio = ratio + &
            reflecting_tail(d_dt_scaled) - reflecting_tail(TABLE_MAX)
        if (d_tp_scaled > TABLE_MAX) ratio = ratio + &
            absorbing_tail(d_tp_scaled) - absorbing_tail(TABLE_MAX)
    end function layer_ratio

    pure function narrow_layer_ratio(a, b) result(ratio)
        real(dp), intent(in) :: a, b
        real(dp) :: ratio

        if (.not. ieee_is_finite(a) .or. .not. ieee_is_finite(b)) &
            error stop 'collisional layer requires finite scaled distances'
        if (min(a, b) < 0.0_dp) &
            error stop 'collisional layer requires nonnegative scaled distances'
        if (max(a, b) <= NARROW_MAX) then
            if (a + b <= NARROW_MAX) then
                ratio = (a + b)**3/(3.0_dp*pi)
                return
            end if
        end if
        ratio = -1.0_dp
    end function narrow_layer_ratio

    pure function interpolated_ratio(a, b) result(ratio)
        real(dp), intent(in) :: a, b
        real(dp) :: ratio, wa(4), wb(4)
        integer :: ia, ib, j, k

        call cubic_weights(a, ia, wa)
        call cubic_weights(b, ib, wb)
        ratio = 0.0_dp
        do k = 1, 4
            do j = 1, 4
                ratio = ratio + wa(j)*wb(k)*log(R_TABLE(ia+j-1, ib+k-1))
            end do
        end do
        ratio = exp(ratio)
    end function interpolated_ratio

    pure function reflecting_tail(a) result(tail)
        ! Particular-solution tail plus Neumann endpoint layer, through a^(-9/2).
        real(dp), intent(in) :: a
        real(dp) :: tail
        tail = -a**(-3)/(3.0_dp*pi) - a**(-4.5_dp)/(sqrt(2.0_dp)*pi)
    end function reflecting_tail

    pure function absorbing_tail(b) result(tail)
        ! Dirichlet endpoint layer and particular tail, through b^(-3).
        real(dp), intent(in) :: b
        real(dp) :: tail
        tail = b**(-1.5_dp)/(sqrt(2.0_dp)*pi) + 17.0_dp*b**(-3)/(12.0_dp*pi)
    end function absorbing_tail

    pure subroutine cubic_weights(distance, idx, weights)
        real(dp), intent(in) :: distance
        integer, intent(out) :: idx
        real(dp), intent(out) :: weights(4)
        real(dp) :: t, x, nodes(4)
        integer :: j, k

        if (distance < TABLE_MIN) then
            idx = 1
            x = distance
            nodes = [0.0_dp, TABLE_MIN, TABLE_MIN*2.0_dp**LOG2_STEP, &
                TABLE_MIN*2.0_dp**(2.0_dp*LOG2_STEP)]
        else
            t = (log(distance)/LOG2_OF_2 - LOG2_MIN)/LOG2_STEP
            idx = max(2, min(int(t) + 1, NGRID - 3))
            x = t - real(idx - 2, dp)
            nodes = [0.0_dp, 1.0_dp, 2.0_dp, 3.0_dp]
        end if
        do j = 1, 4
            weights(j) = 1.0_dp
            do k = 1, 4
                if (j /= k) weights(j) = weights(j)*(x - nodes(k))/(nodes(j) - nodes(k))
            end do
        end do
    end subroutine cubic_weights

    function deflection_frequency(v) result(nu_d)
        ! Use the same all-background SI kernel as main's mixture rates.
        use neort_collision_rates, only: collision_rates_t, initialize_collision_rates, &
            rate => deflection_frequency
        use neort_species, only: mixture_enabled, mixture_at_s, species_mixture, &
            selected_species
        use neort_profiles, only: profile_species
        real(dp), intent(in) :: v  ! cm/s
        real(dp) :: nu_d
        type(collision_rates_t) :: background
        integer :: selected

        if (mixture_enabled) then
            if (.not. allocated(mixture_at_s)) &
                error stop 'collisional layer requires evaluated mixture profiles'
            call initialize_collision_rates(mixture_at_s%mass_kg, mixture_at_s%charge_e, &
                mixture_at_s%density_m3, mixture_at_s%temperature_ev, &
                species_mixture%coulomb_log, background)
            selected = selected_species
        else
            call legacy_collision_background(background)
            selected = profile_species + 1
        end if
        nu_d = rate(background, selected, v*0.01_dp)
    end function deflection_frequency

    subroutine legacy_collision_background(background)
        use neort_collision_rates, only: collision_rates_t, initialize_collision_rates
        use neort_profiles, only: ni1, ni2, Ti1, Ti2, Te, am1_global, am2_global, &
            Z1_global, Z2_global, electron_mass
        use util, only: mu
        type(collision_rates_t), intent(out) :: background
        real(dp) :: ne, ln_lambda

        ne = Z1_global*ni1 + Z2_global*ni2
        if (ne <= 0.0_dp .or. Te <= 0.0_dp) &
            error stop 'collisional layer requires positive plasma profiles'
        ln_lambda = max(1.0_dp, 24.0_dp - log(sqrt(ne)/Te))
        call initialize_collision_rates( &
            [electron_mass, am1_global*mu, am2_global*mu]*0.001_dp, &
            [-1.0_dp, Z1_global, Z2_global], [ne, ni1, ni2]*1.0e6_dp, &
            [Te, Ti1, Ti2], ln_lambda, background)
    end subroutine legacy_collision_background

    pure elemental function comp_ellint_k(m) result(k)
        ! Complete elliptic integral K(m), parameter (m = k^2) convention.
        ! Abramowitz & Stegun 17.3.34, |error| < 3e-8 for m in [0, 1).
        real(dp), intent(in) :: m
        real(dp) :: k
        real(dp) :: m1, log_term
        real(dp), parameter :: a0 = 1.38629436112_dp, a1 = 0.09666344259_dp, &
            a2 = 0.03590092383_dp, a3 = 0.03742563713_dp, a4 = 0.01451196212_dp
        real(dp), parameter :: b0 = 0.5_dp, b1 = 0.12498593597_dp, &
            b2 = 0.06880248576_dp, b3 = 0.03328355346_dp, b4 = 0.00441787012_dp

        m1 = 1.0_dp - m
        log_term = -log(m1)
        k = (a0 + m1*(a1 + m1*(a2 + m1*(a3 + m1*a4)))) &
            + log_term*(b0 + m1*(b1 + m1*(b2 + m1*(b3 + m1*b4))))
    end function comp_ellint_k

    pure elemental function comp_ellint_e(m) result(e)
        ! Complete elliptic integral E(m), parameter (m = k^2) convention.
        ! Abramowitz & Stegun 17.3.36, |error| < 2e-8 for m in [0, 1).
        real(dp), intent(in) :: m
        real(dp) :: e
        real(dp) :: m1, log_term
        real(dp), parameter :: a1 = 0.44325141463_dp, a2 = 0.06260601220_dp, &
            a3 = 0.04757383546_dp, a4 = 0.01736506451_dp
        real(dp), parameter :: b1 = 0.24998368310_dp, b2 = 0.09200180037_dp, &
            b3 = 0.04069697526_dp, b4 = 0.00526449639_dp

        m1 = 1.0_dp - m
        log_term = -log(m1)
        e = (1.0_dp + m1*(a1 + m1*(a2 + m1*(a3 + m1*a4)))) &
            + log_term*(m1*(b1 + m1*(b2 + m1*(b3 + m1*b4))))
    end function comp_ellint_e

